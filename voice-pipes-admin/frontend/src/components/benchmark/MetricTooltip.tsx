  'Avg E2E':      'Average end-to-end latency across all repetitions of a scenario.',
  'Avg TTFT':     'Average Time to First Token — how long until the LLM starts generating.',
  'Avg TTFB':     'Average Time to First Byte of audio — how long until TTS starts producing sound.',
  'TTFT':         'Time to First Token — how long until the LLM starts generating a response.',
  'TTFB':         'Time to First Byte — how long until the TTS engine starts producing audio.',
  'E2E Latency':  'End-to-end latency — total time from audio injection to final pipeline output.',
  'WER':          'Word Error Rate — percentage of words incorrectly transcribed vs. the expected text.',
  'Pass Rate':    'Percentage of scenarios that met all expected outcomes.',
  'STT Text':     'The text produced by the speech-to-text stage.',
  'Response':     'The text generated by the LLM in response to the transcription.',
  'Status':       'Whether the scenario passed, failed expectations, timed out, or encountered an error.',
  'Failures':     'List of expectations that were not met for this scenario.',
