//! The stack manifest — the wizard's single declarative hand-off to the
//! launcher scripts.
//!
//! Instead of one bespoke flag file per sidecar (each hand-decoded in two
//! shell dialects), the wizard writes `stack-manifest.env` describing *what*
//! the launcher must start. Both `launch-stack.ps1` and `launch-stack.sh`
//! parse it generically, so adding a new sidecar to the wizard never requires
//! editing them.
//!
//! Format: flat `KEY="VALUE"` lines (sourceable by POSIX sh, trivially
//! parseable in PowerShell). Reserved keys, always present:
//!
//! - `COMPOSE_PROFILES` — comma-separated compose profiles to activate
//!   (docker compose reads this env var natively).
//! - `SIDECAR_SERVICES` — space-separated service names to pass to
//!   `docker compose up` (profiles alone don't pull services into an `up`
//!   with explicit service names).
//! - `REQUIRES_GPU` — space-separated services that need GPU pass-through;
//!   the launcher warns when its GPU probe failed.
//! - `ENSURE_DIRS` — space-separated bind-mount source dirs (relative to
//!   `voice-pipes/`) the launcher pre-creates so Docker doesn't create them
//!   root-owned.
//!
//! Any other key (e.g. `LLAMA_MODEL`) is exported to the environment verbatim
//! for docker-compose interpolation.

use std::fmt::Write as _;

/// Manifest file name, under `deploy/docker/config/`.
pub const MANIFEST_FILE: &str = "stack-manifest.env";

/// Flag files written by older wizard versions, superseded by the manifest.
/// The wizard removes them so a stale flag can't confuse an old launcher.
pub const LEGACY_FLAG_FILES: &[&str] = &[
    ".llama-server-model",
    ".pocket-tts-enabled",
    ".vibevoice-enabled",
    ".smart-turn-enabled",
];

/// Reserved manifest keys (everything else is exported as an env var).
#[cfg_attr(
    not(test),
    expect(
        dead_code,
        reason = "contract constant; consumed by the round-trip coverage tests"
    )
)]
pub const RESERVED_KEYS: &[&str] = &[
    "COMPOSE_PROFILES",
    "SIDECAR_SERVICES",
    "REQUIRES_GPU",
    "ENSURE_DIRS",
];

#[derive(Debug, Default, Clone, PartialEq, Eq)]
pub struct StackManifest {
    pub profiles: Vec<String>,
    pub services: Vec<String>,
    pub requires_gpu: Vec<String>,
    pub ensure_dirs: Vec<String>,
    /// Extra env vars for docker-compose interpolation (e.g. `LLAMA_MODEL`).
    pub env: Vec<(String, String)>,
}

impl StackManifest {
    pub fn render(&self) -> String {
        let mut out = String::from(
            "# Generated by voice-pipes config-wizard. Consumed generically by\n\
             # launch-stack.ps1 / launch-stack.sh — adding a sidecar never requires\n\
             # editing the launchers. Paths are relative to voice-pipes/.\n",
        );
        let mut line = |key: &str, value: &str| {
            let _ = writeln!(out, "{key}=\"{value}\"");
        };
        line("COMPOSE_PROFILES", &self.profiles.join(","));
        line("SIDECAR_SERVICES", &self.services.join(" "));
        line("REQUIRES_GPU", &self.requires_gpu.join(" "));
        line("ENSURE_DIRS", &self.ensure_dirs.join(" "));
        for (key, value) in &self.env {
            line(key, value);
        }
        out
    }
}
