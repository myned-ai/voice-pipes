/// Keys are saved before the config files, `.env` is owner-only, and an
/// existing generated config is not overwritten without a yes.
#[test]
fn write_outputs_saves_keys_privately_and_asks_before_overwriting() {
    let plan = plan_for(&[]);
    let plan = WizardPlan {
        env_to_save: vec![("ASSEMBLYAI_API_KEY".into(), "sk-1".into())],
        ..plan
    };
    let tmp = tempfile::tempdir().unwrap();
    let root = tmp.path();
    fs::write(
        root.join(".env"),
        "VP_CLIENT_TOKEN=abc\nASSEMBLYAI_API_KEY=old\n",
    )
    .unwrap();

    // First run: nothing exists yet, no question asked.
    let asking = AutoPrompt::new(&[]);
    let written = super::write_outputs(&plan, root, &asking)
        .unwrap()
        .expect("written");
    assert!(written.pipeline.exists() && written.worker.exists() && written.manifest.exists());
    assert!(asking.asked.borrow().is_empty());
    let env = fs::read_to_string(root.join(".env")).unwrap();
    assert_eq!(env, "VP_CLIENT_TOKEN=abc\nASSEMBLYAI_API_KEY=sk-1\n");
    assert!(!root.join(".env.tmp").exists());
    #[cfg(unix)]
    assert_eq!(
        std::os::unix::fs::PermissionsExt::mode(
            &fs::metadata(root.join(".env")).unwrap().permissions()
        ) & 0o777,
        0o600,
        ".env must be owner-only"
    );

    // Second run: the files exist; declining leaves them untouched.
    fs::write(&written.pipeline, "# hand-edited\n").unwrap();
    let declining = ConfirmingPrompt {
        inner: AutoPrompt::new(&[]),
        answer_for: "Overwrite",
        answer: false,
    };
    assert!(
        super::write_outputs(&plan, root, &declining)
            .unwrap()
            .is_none()
    );
    assert_eq!(
        fs::read_to_string(&written.pipeline).unwrap(),
        "# hand-edited\n"
    );

    // Accepting replaces them.
    let accepting = ConfirmingPrompt {
        inner: AutoPrompt::new(&[]),
        answer_for: "Overwrite",
        answer: true,
    };
    assert!(
        super::write_outputs(&plan, root, &accepting)
            .unwrap()
            .is_some()
    );
    assert_eq!(
        fs::read_to_string(&written.pipeline).unwrap(),
        plan.pipeline_toml
    );

    let archive_dir = root.join("deploy/docker/config/archive");
    assert!(archive_dir.is_dir());
    let mut entries: Vec<_> = fs::read_dir(&archive_dir)
        .unwrap()
        .map(|e| e.unwrap().path())
        .collect();
    assert_eq!(entries.len(), 1);
    let archived_pipeline = entries.pop().unwrap().join("pipeline-custom.toml");
    assert_eq!(
        fs::read_to_string(archived_pipeline).unwrap(),
        "# hand-edited\n"
    );
}

