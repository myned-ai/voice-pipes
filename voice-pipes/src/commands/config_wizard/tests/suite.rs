/// Prompt that accepts every default, answers "" to secrets, and lets a test
/// force specific menu selections by prompt title.
struct AutoPrompt {
    selects: HashMap<&'static str, usize>,
    asked: RefCell<Vec<String>>,
}

impl AutoPrompt {
    fn new(selects: &[(&'static str, usize)]) -> Self {
        Self {
            selects: selects.iter().copied().collect(),
            asked: RefCell::new(Vec::new()),
        }
    }
}

impl Prompt for AutoPrompt {
    fn select(&self, prompt: &str, items: &[&str], default: usize) -> Result<usize> {
        self.asked.borrow_mut().push(prompt.to_string());
        let idx = self.selects.get(prompt).copied().unwrap_or(default);
        assert!(
            idx < items.len(),
            "forced index {idx} out of range for {prompt:?}"
        );
        Ok(idx)
    }

    fn text(&self, _prompt: &str, default: &str) -> Result<String> {
        Ok(default.to_string())
    }

    fn password(&self, _prompt: &str) -> Result<String> {
        Ok(String::new())
    }

    fn confirm(&self, _prompt: &str, default: bool) -> Result<bool> {
        Ok(default)
    }
}

/// The model registry, with every stub plugin registered. The registry is
/// process-wide and the menus and stages the wizard shows depend on what
/// is in it, so every test sees all the stubs, whichever ran before it or
/// whether it runs alone. (The wizard's LLM stage has no built-in entry, so
/// a classic plan needs the stub text processor in any case.)
fn test_registry() -> Registry {
    register_every_stub();
    load_model_registry()
}

/// Register each stub plugin the wizard tests use, once per process.
fn register_every_stub() {
    crate::vad::segmenter::stand_in::register();
    register_wizard_stub_voice_once();
    register_wizard_stub_once();
    register_wizard_stub_tts_once();
    register_wizard_stub_sidecar_once();
    register_wizard_stub_model_sidecar_once();
    register_wizard_stub_s2s_once();
    register_wizard_stub_llm_once();
    // Last, so the menu order test sees rank win over registration order.
    register_wizard_stub_recogniser_once();
}

/// Builds a plan accepting all defaults except the forced menu selections.
fn plan_for(selects: &[(&'static str, usize)]) -> WizardPlan {
    let registry = test_registry();
    let prompt = AutoPrompt::new(selects);
    build_plan(&prompt, &registry).expect("wizard plan builds")
}

/// A stage's built-in entries, with the provider each selects.
fn table(stage: Stage) -> Vec<(String, WizardChoice)> {
    super::providers::builtin_choices(stage)
}

/// An STT choice's index in the menu the tests' registry shows, by its
/// label's start.
fn stt_idx(label: &str) -> usize {
    register_every_stub();
    super::menu(Stage::Stt)
        .iter()
        .position(|(_, l)| l.starts_with(label))
        .unwrap_or_else(|| panic!("no STT choice labelled {label:?}"))
}

fn all_tables() -> [(&'static str, Vec<(String, WizardChoice)>); 4] {
    [
        ("STT", table(Stage::Stt)),
        ("LLM", table(Stage::Llm)),
        ("TTS", table(Stage::Tts)),
        ("turn", table(Stage::Turn)),
    ]
}

