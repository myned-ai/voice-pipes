/// A plugin that declares its files gets them fetched like a built-in's: the
/// registry gains its entry, and choosing it queues both files, the second
/// next to the model path.
#[test]
fn a_plugins_declared_files_are_queued_for_download() {
    register_wizard_stub_tts_once();
    let registry = test_registry();
    let entry = registry
        .get("wizard-stub-tts")
        .expect("plugin entry merged");
    assert_eq!(entry.default_path, "models/stub-voice.onnx");
    assert_eq!(entry.layout, Layout::File);

    let plan = plan_for(&[("Choose TTS Provider", tts_plugin_idx("wizard-stub-tts"))]);
    assert!(
        plan.pipeline_toml.contains(
            "[tts]\nprovider = \"wizard-stub-tts\"\nmodel = \"models/stub-voice.onnx\"\n"
        ),
        "{}",
        plan.pipeline_toml
    );
    let spec = plan
        .downloads
        .iter()
        .find(|d| d.registry_key == "wizard-stub-tts")
        .expect("queued");
    assert_eq!(spec.dest, "models/stub-voice.onnx");

    let tmp = tempfile::tempdir().unwrap();
    let missing = plan_missing_downloads(std::slice::from_ref(spec), &registry, tmp.path());
    let dests: Vec<_> = missing.iter().map(|m| m.dest.clone()).collect();
    assert_eq!(
        dests,
        vec![
            tmp.path().join("models/stub-voice.onnx"),
            tmp.path().join("models").join("stub-voices.bin"),
        ]
    );
}

