    let builtins = table(Stage::Stt);
    let menu = super::StageMenu {
        stage: Stage::Stt,
        choices: builtins
            .iter()
            .cloned()
            .chain(
                wizard_stub_default_stt_choices()
                    .into_iter()
                    .map(|c| ("wizard-stub-default-stt".to_string(), c)),
            )
            .map(|(provider, choice)| super::MenuChoice { provider, choice })
            .collect(),
    };
    let labels: Vec<&str> = menu.choices[builtins.len()..]
        .iter()
        .map(|p| p.choice.label.as_str())
        .collect();
