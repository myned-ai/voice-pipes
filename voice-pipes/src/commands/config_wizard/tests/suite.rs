/// Every menu path must yield a pipeline TOML the engine parses, with no
/// "unknown provider/mode" validation errors (other validation errors — e.g.
/// a missing API key in the test environment — are environmental and
/// ignored). Both files are parsed for every choice whatever features the
/// test build has; only the provider-resolution check needs the feature.
/// Covers the recording-off and tools-off variants as well.
#[test]
fn every_choice_yields_a_parseable_valid_config() {
    // Fillers for the other stages, all in the crate's default feature set.
    let fillers: &[(&'static str, usize)] = &[
        ("Choose STT Provider", 0),       // the stub recogniser
        ("Choose LLM/Text Processor", 0), // the stub plugin
        ("Choose TTS Provider", 0),       // the stub voice
        ("Choose turn detection", 0),     // Layered
    ];

    #[expect(
        clippy::type_complexity,
        reason = "table-driven test cases; an alias would relocate, not simplify"
    )]
    let mut cases: Vec<(Vec<(&'static str, usize)>, Option<String>)> = Vec::new();
    for stage in [Stage::Stt, Stage::Llm, Stage::Tts, Stage::Turn] {
        let title = stage.menu_title();
        for (idx, (_, choice)) in table(stage).into_iter().enumerate() {
            let mut selects: Vec<(&'static str, usize)> = fillers
                .iter()
                .filter(|(s, _)| *s != title)
                .copied()
                .collect();
            selects.push((title, idx));
            cases.push((selects, choice.feature));
        }
    }
    // Speech-to-speech entries are all plugins; the stub stands for them.
    #[cfg(feature = "realtime")]
    cases.push((
        vec![
            ("Select Pipeline Mode", 1),
            ("Choose S2S Provider", s2s_plugin_idx("wizard-stub-s2s")),
        ],
        None,
    ));

    // A classic plan also carries the fillers, so whether its providers
    // resolve is only a question when those are built.
    let table_for = |title: &str| {
        let stage = [Stage::Stt, Stage::Llm, Stage::Tts, Stage::Turn]
            .into_iter()
            .find(|s| s.menu_title() == title)
            .expect("a classic stage");
        table(stage)
    };
    let fillers_compiled = fillers.iter().all(|(title, idx)| {
        table_for(title)
            .get(*idx)
            .is_none_or(|(_, c)| c.feature.as_deref().is_none_or(feature_enabled))
    });

    for (selects, feature) in cases {
        let classic = !selects.contains(&("Select Pipeline Mode", 1));
        let compiled =
            feature.as_deref().is_none_or(feature_enabled) && (!classic || fillers_compiled);
        for (record, tools) in [(true, true), (false, false), (true, false), (false, true)] {
            let prompt = VariantPrompt {
                inner: AutoPrompt::new(&selects),
                record,
                tools,
            };
            let registry = test_registry();
            let plan = build_plan(&prompt, &registry)
                .unwrap_or_else(|e| panic!("{selects:?} record={record} tools={tools}: {e}"));
            let cfg: crate::config::PipelineConfig = toml::from_str(&plan.pipeline_toml)
                .unwrap_or_else(|e| panic!("{selects:?}: generated TOML does not parse: {e}"));
            let _: crate::api::types::WorkerConfig = toml::from_str(&plan.worker_toml)
                .unwrap_or_else(|e| panic!("{selects:?}: worker TOML does not parse: {e}"));
            assert_eq!(cfg.pipeline.audit.enabled, record, "{selects:?}");
            assert_eq!(cfg.client_tool.is_empty(), !tools, "{selects:?}");
            assert!(
                cfg.output
                    .as_ref()
                    .and_then(|o| o.chunking.as_ref())
                    .is_some_and(|c| c.enabled),
                "{selects:?}: output chunking must be on in the pipeline config"
            );
            if compiled {
                let errors = crate::config::validate(&cfg);
                let unknown: Vec<_> = errors
                    .iter()
                    .filter(|e| e.kind == crate::config::ConfigErrorKind::UnknownName)
                    .collect();
                assert!(
                    unknown.is_empty(),
                    "{selects:?}: provider/mode does not resolve: {unknown:?}"
                );
            }
        }
    }
}

/// An [`AutoPrompt`] with explicit answers for the two yes/no questions
/// every path asks.
struct VariantPrompt {
    inner: AutoPrompt,
    record: bool,
    tools: bool,
}

impl Prompt for VariantPrompt {
    fn select(&self, prompt: &str, items: &[&str], default: usize) -> Result<usize> {
        self.inner.select(prompt, items, default)
    }
    fn text(&self, prompt: &str, default: &str) -> Result<String> {
        self.inner.text(prompt, default)
    }
    fn password(&self, prompt: &str) -> Result<String> {
        self.inner.password(prompt)
    }
    fn confirm(&self, prompt: &str, default: bool) -> Result<bool> {
        if prompt.starts_with("Record sessions") {
            return Ok(self.record);
        }
        if prompt.starts_with("Add demo client-side tools") {
            return Ok(self.tools);
        }
        self.inner.confirm(prompt, default)
    }
}

