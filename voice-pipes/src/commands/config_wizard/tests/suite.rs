/// Every offered provider's feature must be compiled into both worker images
/// (directly, via its `-cuda` variant, or as a crate default feature).
/// This is the "unknown or disabled … provider" launch failure, made a CI
/// failure instead.
#[test]
fn every_choice_feature_is_in_the_worker_images() {
    let compose = compose_text();
    let defaults = default_features();

    // The workers' list, defined once (`- &name FEATURES=...`), and the
    // other images' lists. The CUDA image builds the workers' list with the
    // GPU switches on top, so a feature in it is in both images.
    let features: Vec<String> = compose
        .lines()
        .filter_map(|l| {
            let item = l.trim().strip_prefix("- ")?;
            let item = item
                .strip_prefix('&')
                .and_then(|a| a.split_once(' ').map(|(_, rest)| rest))
                .unwrap_or(item);
            item.strip_prefix("FEATURES=")
        })
        .flat_map(|l| l.split(','))
        .map(|f| f.trim().to_string())
        .collect();
    assert!(
        !features.is_empty(),
        "no FEATURES= build args found in docker-compose.yml"
    );

    for (stage, table) in all_tables() {
        for (_, choice) in table {
            let Some(feature) = choice.feature.as_deref() else {
                continue;
            };
            assert!(
                features.iter().any(|f| f == feature) || defaults.iter().any(|f| f == feature),
                "{stage} choice {:?}: feature {feature:?} is not in the worker FEATURES \
                 (deploy/docker/docker-compose.yml) or crate default features",
                choice.label
            );
        }
    }
}

