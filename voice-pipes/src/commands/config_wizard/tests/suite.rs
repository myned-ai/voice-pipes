/// Every workspace member must be copied into both worker images' build
/// context, or every container build fails with "failed to load manifest",
/// and nothing but the container build would notice. The Dockerfiles copy
/// crates by pattern (`voice-pipes*/Cargo.toml`), so this holds each member
/// to a copy that names it or a pattern that matches its manifest -- a crate
/// named outside the pattern is what it catches.
#[test]
fn every_workspace_member_is_copied_into_the_worker_images() {
    /// `*` matches any run of characters within one path segment.
    fn segment_matches(pattern: &str, name: &str) -> bool {
        match pattern.split_once('*') {
            None => pattern == name,
            Some((head, tail)) => {
                name.len() >= head.len() + tail.len()
                    && name.starts_with(head)
                    && name.ends_with(tail)
            }
        }
    }

    let cargo = repo_file("Cargo.toml");
    let members_block = cargo
        .split_once("members = [")
        .and_then(|(_, rest)| rest.split_once(']'))
        .map(|(block, _)| block)
        .expect("workspace members list in the root Cargo.toml");
    let members: Vec<&str> = members_block.split('"').skip(1).step_by(2).collect();
    assert!(members.contains(&"voice-pipes"), "{members:?}");

    for dockerfile in ["voice-pipes/Dockerfile", "voice-pipes/Dockerfile.cuda"] {
        let text = repo_file(dockerfile);
        let copy_args: Vec<&str> = text
            .lines()
            .map(str::trim)
            .filter(|l| l.starts_with("COPY ") && !l.contains("--from="))
            .flat_map(|l| {
                l.split_whitespace()
                    .skip(1)
                    .filter(|a| !a.starts_with("--"))
            })
            .collect();
        for member in &members {
            let target_manifest = format!("{member}/Cargo.toml");
            let target_segs: Vec<&str> = target_manifest.split('/').collect();
            let copied = copy_args.iter().any(|arg| {
                let arg_segs: Vec<&str> = arg.split('/').collect();
                *arg == *member
                    || arg.starts_with(&format!("{member}/"))
                    || (arg_segs.len() == target_segs.len()
                        && arg_segs
                            .iter()
                            .zip(&target_segs)
                            .all(|(pat, name)| segment_matches(pat, name)))
            });
            assert!(
                copied,
                "{dockerfile} does not COPY workspace member `{member}`; the container build \
                 fails with `failed to load manifest for dependency` without it"
            );
        }
    }
}

/// Every workspace crate that logs must be named in both images' `RUST_LOG`.
/// A filter directive for `voice_pipes` does not reach `voice_pipes_stt_x`, so
/// a crate left out logs nothing inside a container -- its connects, retries
/// and errors silently dropped -- and nothing but reading container logs
/// would notice.
#[test]
fn every_logging_workspace_crate_is_named_in_the_images_rust_log() {
    let cargo = repo_file("Cargo.toml");
    let members_block = cargo
        .split_once("members = [")
        .and_then(|(_, rest)| rest.split_once(']'))
        .map(|(block, _)| block)
        .expect("workspace members");
    let logging: Vec<String> = members_block
        .split('"')
        .skip(1)
        .step_by(2)
        .filter_map(|m| {
            let manifest: toml::Table = repo_file(&format!("{m}/Cargo.toml"))
                .parse()
                .unwrap_or_else(|e| panic!("{m}/Cargo.toml: {e}"));
            let logs = manifest
                .get("dependencies")
                .and_then(toml::Value::as_table)
                .is_some_and(|deps| deps.contains_key("tracing"));
            logs.then(|| {
                manifest["package"]["name"]
                    .as_str()
                    .unwrap_or_else(|| panic!("{m}/Cargo.toml has no package.name"))
                    .to_string()
            })
        })
        .collect();
    assert!(logging.iter().any(|m| m == "voice-pipes"), "{logging:?}");

    for dockerfile in ["voice-pipes/Dockerfile", "voice-pipes/Dockerfile.cuda"] {
        let text = repo_file(dockerfile);
        let rust_log = text
            .lines()
            .find_map(|l| l.trim().strip_prefix("ENV RUST_LOG="))
            .unwrap_or_else(|| panic!("{dockerfile} sets no RUST_LOG"));
        let targets: Vec<&str> = rust_log
            .split(',')
            .filter_map(|d| d.split('=').next())
            .collect();
        for member in &logging {
            let target = member.replace('-', "_");
            assert!(
                targets.contains(&target.as_str()),
                "{dockerfile}: RUST_LOG does not name `{target}`, so `{member}` logs nothing in the image"
            );
        }
    }
}

/// A member named outside the Dockerfiles' crate pattern would be missed by
