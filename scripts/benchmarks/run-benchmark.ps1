<#
.SYNOPSIS
    Create and run a voice-pipes benchmark experiment.

.DESCRIPTION
    This script:
    1. Checks that the orchestrator is reachable
    2. Verifies at least one worker is registered
    3. Creates (or reuses) a test suite with audio scenarios
    4. Creates a new experiment
    5. Runs the experiment
    6. Polls for completion and prints results

.PARAMETER OrchestratorUrl
    Base URL of the orchestrator API (default: http://127.0.0.1:9090)

.PARAMETER ConfigPath
    Path to the pipeline TOML config for the variant (default: examples/dev/test-live-gemma4.toml)

.PARAMETER VariantName
    Friendly name for the variant under test (default: "Gemma 4 E2B")

.PARAMETER AudioFiles
    Array of WAV file paths to use as test scenarios. Defaults to hello.wav in the workspace root.

.PARAMETER Repetitions
    Number of times to repeat each scenario (default: 3)

.PARAMETER TimeoutS
    Per-scenario timeout in seconds (default: 120)

.PARAMETER PollIntervalS
    How often to poll for completion in seconds (default: 5)

.PARAMETER MaxWaitS
    Maximum time to wait for experiment completion in seconds (default: 600)

.EXAMPLE
    .\run-benchmark.ps1

.EXAMPLE
    .\run-benchmark.ps1 -AudioFiles hello.wav, test_speech.wav -Repetitions 5

.EXAMPLE
    .\run-benchmark.ps1 -ConfigPath examples/dev/test-live-llama.toml -VariantName "Llama 3.2 3B"
#>

param(
    [string]$OrchestratorUrl = "http://127.0.0.1:9090",
    [string]$ConfigPath = "examples/dev/test-live-gemma4.toml",
    [string]$VariantName = "Gemma 4 E2B",
    [string[]]$AudioFiles = @("examples/audio/hello.wav"),
    [int]$Repetitions = 3,
    [int]$TimeoutS = 120,
    [int]$PollIntervalS = 5,
    [int]$MaxWaitS = 600,
    [string]$LlmServerUrl = "http://localhost:8081",
    [string[]]$ScenarioIds = @()
)

$ErrorActionPreference = "Stop"
# Orchestrator admin API needs VP_ADMIN_TOKEN (env or voice-pipes/.env).
. (Join-Path $PSScriptRoot "../admin-auth.ps1")
$api = "$OrchestratorUrl/api/v1"

function Write-Step($msg) { Write-Host "`n==> $msg" -ForegroundColor Cyan }
function Write-Ok($msg)   { Write-Host "    OK: $msg" -ForegroundColor Green }
function Write-Fail($msg) { Write-Host "    FAIL: $msg" -ForegroundColor Red; exit 1 }

# ── 1. Health check ──────────────────────────────────────────
Write-Step "Checking LLM server at $LlmServerUrl ..."
try {
    $llmHealth = Invoke-WebRequest -Uri "$LlmServerUrl/health" -TimeoutSec 3 -ErrorAction Stop
    if ($llmHealth.StatusCode -eq 200) {
        Write-Ok "LLM server is already running"
    } else {
        Write-Fail "LLM server responded with status $($llmHealth.StatusCode). Check llama-server."
    }
} catch {
    Write-Fail "LLM server not reachable at $LlmServerUrl. Start llama-server first (e.g. .\run-live-gemma4.ps1)."
}

Write-Step "Checking orchestrator health..."
try {
    $health = Invoke-RestMethod "$api/health"
    Write-Ok "Orchestrator is up"
} catch {
    Write-Fail "Cannot reach orchestrator at $OrchestratorUrl. Is it running?"
}

# ── 2. Verify workers ───────────────────────────────────────
Write-Step "Checking for registered workers..."
try {
    $workers = Invoke-RestMethod "$api/workers"
    $total = $workers.data.total
    if ($total -lt 1) {
        Write-Fail "No workers registered. Start a worker first."
    }
    Write-Ok "$total worker(s) registered"
} catch {
    Write-Fail "Failed to query workers: $_"
}

# ── 3. Create test suite ────────────────────────────────────
Write-Step "Creating test suite..."

# Build scenarios from the audio file list
$scenarios = @()
foreach ($file in $AudioFiles) {
    # Resolve to absolute path for reliable loading
    $resolved = (Resolve-Path $file -ErrorAction SilentlyContinue)
    if (-not $resolved) {
        Write-Fail "Audio file not found: $file"
    }
    $absPath = $resolved.Path
    $scenarioName = [System.IO.Path]::GetFileNameWithoutExtension($file)
    $scenarios += @{
        id   = $scenarioName
        name = $scenarioName
        input = @{
            type = "audio_file"
            path = $absPath
        }
    }
}

$suiteBody = @{
    name        = "Benchmark Suite $(Get-Date -Format 'yyyy-MM-dd HH:mm')"
    description = "Auto-generated by run-benchmark.ps1"
    scenarios   = $scenarios
} | ConvertTo-Json -Depth 5

try {
    $suite = Invoke-RestMethod -Method POST -Uri "$api/benchmark/suites" `
        -ContentType "application/json" -Body $suiteBody
    $suiteId = $suite.data.id
    if (-not $suiteId) { $suiteId = $suite.id }
    Write-Ok "Suite created: $suiteId"
} catch {
    Write-Fail "Failed to create test suite: $_"
}

# ── 4. Create experiment ────────────────────────────────────
Write-Step "Creating experiment..."

# Derive a variant ID from the name
$variantId = ($VariantName -replace '\s+', '-').ToLower()

$expBody = @{
    name          = "$VariantName Benchmark $(Get-Date -Format 'yyyy-MM-dd HH:mm')"
    test_suite_id = $suiteId
    variants      = @(@{
        id          = $variantId
        name        = $VariantName
        config_path = $ConfigPath
        config_hash = ""
        tags        = @()
    })
    repetitions = $Repetitions
} | ConvertTo-Json -Depth 5

try {
    $exp = Invoke-RestMethod -Method POST -Uri "$api/benchmark/experiments" `
        -ContentType "application/json" -Body $expBody
    $expId = $exp.data.id
    if (-not $expId) { $expId = $exp.id }
    Write-Ok "Experiment created: $expId"
} catch {
    Write-Fail "Failed to create experiment: $_"
}

# ── 5. Run the experiment ───────────────────────────────────
Write-Step "Starting experiment run..."
try {
    $runUrl = "$api/benchmark/experiments/$expId/run?timeout_s=$TimeoutS"
    if ($ScenarioIds.Count -gt 0) {
        $joined = ($ScenarioIds -join ",")
        $runUrl = "$runUrl&scenarios=$joined"
        Write-Host "    scenarios filter: $joined" -ForegroundColor DarkGray
    }
    $runResult = Invoke-RestMethod -Method POST -Uri $runUrl
    Write-Ok "Experiment started"
} catch {
    Write-Fail "Failed to start experiment: $_"
}

# ── 6. Poll for completion ──────────────────────────────────
Write-Step "Waiting for experiment to complete (polling every ${PollIntervalS}s, max ${MaxWaitS}s)..."

$elapsed = 0
$status = "running"
while ($elapsed -lt $MaxWaitS) {
    Start-Sleep -Seconds $PollIntervalS
    $elapsed += $PollIntervalS

    try {
        $check = Invoke-RestMethod "$api/benchmark/experiments/$expId"
        $expData = $check.data
        if (-not $expData) { $expData = $check }
        $status = $expData.status
    } catch {
        Write-Host "    Poll error: $_ (retrying...)" -ForegroundColor Yellow
        continue
    }

    Write-Host "    [$elapsed s] Status: $status" -ForegroundColor DarkGray

    if ($status -eq "complete" -or $status -eq "failed") {
        break
    }
}

if ($status -eq "running") {
    Write-Fail "Experiment did not complete within ${MaxWaitS}s. Check orchestrator logs."
}

# ── 7. Fetch and display results ────────────────────────────
Write-Step "Fetching results..."

try {
    $results = Invoke-RestMethod "$api/benchmark/experiments/$expId/results"
    $resData = $results.data
    if (-not $resData) { $resData = $results }
} catch {
    Write-Fail "Failed to fetch results: $_"
}

# Pretty-print summary
Write-Host "`n" -NoNewline
Write-Host ("=" * 60) -ForegroundColor White
Write-Host "  BENCHMARK RESULTS" -ForegroundColor White
Write-Host ("=" * 60) -ForegroundColor White

foreach ($vr in $resData.variant_results) {
    Write-Host "`n  Variant: $($vr.variant_name)" -ForegroundColor Yellow
    $s = $vr.summary
    Write-Host "    Scenarios: $($s.scenarios_passed) passed / $($s.scenarios_failed) failed / $($s.scenarios_run) total"

    if ($s.avg_e2e_latency_ms) {
        Write-Host "    Avg E2E Latency:  $([math]::Round($s.avg_e2e_latency_ms, 1)) ms"
    }
    if ($s.p50_e2e_latency_ms) {
        Write-Host "    P50 E2E Latency:  $($s.p50_e2e_latency_ms) ms"
    }
    if ($s.p90_e2e_latency_ms) {
        Write-Host "    P90 E2E Latency:  $($s.p90_e2e_latency_ms) ms"
    }
    if ($s.avg_ttft_ms) {
        Write-Host "    Avg TTFT:         $([math]::Round($s.avg_ttft_ms, 1)) ms"
    }
    if ($s.avg_ttfb_ms) {
        Write-Host "    Avg TTFB:         $([math]::Round($s.avg_ttfb_ms, 1)) ms"
    }
    if ($s.avg_wer) {
        Write-Host "    Avg WER:          $([math]::Round($s.avg_wer, 3))"
    }

    Write-Host "`n    Scenario Details:" -ForegroundColor DarkYellow
    foreach ($sc in $vr.scenarios) {
        $icon = if ($sc.status -eq "passed") { "[PASS]" } else { "[FAIL]" }
        $color = if ($sc.status -eq "passed") { "Green" } else { "Red" }
        Write-Host "      $icon $($sc.scenario_name)" -ForegroundColor $color

        $m = $sc.metrics
        if ($m.stt_text)       { Write-Host "           STT:     `"$($m.stt_text)`"" }
        if ($m.response_text)  { Write-Host "           LLM:     `"$($m.response_text.Substring(0, [Math]::Min(100, $m.response_text.Length)))`"..." }
        if ($m.e2e_latency_ms) { Write-Host "           E2E:     $([math]::Round($m.e2e_latency_ms, 1)) ms" }
        if ($m.ttft_ms)        { Write-Host "           TTFT:    $([math]::Round($m.ttft_ms, 1)) ms" }
        if ($m.ttfb_ms)        { Write-Host "           TTFB:    $([math]::Round($m.ttfb_ms, 1)) ms" }
    }
}

Write-Host "`n$("=" * 60)" -ForegroundColor White
Write-Host "  Experiment ID: $expId"
Write-Host "  Full JSON:     $api/benchmark/experiments/$expId/results"
Write-Host ("=" * 60) -ForegroundColor White

# Also dump the raw JSON to a file for later analysis
$outFile = "benchmark-results-$(Get-Date -Format 'yyyyMMdd-HHmmss').json"
$resData | ConvertTo-Json -Depth 15 | Set-Content $outFile -Encoding UTF8
Write-Host "`n  Results saved to $outFile`n" -ForegroundColor Green
