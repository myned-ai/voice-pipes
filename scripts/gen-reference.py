#!/usr/bin/env python3
"""Generate the enumerable parts of docs/reference/ from the code, and check
hand-written reference pages for drift.

Generated (between `<!-- generated:start NAME -->` / `<!-- generated:end NAME -->`
markers, so the prose around them stays hand-written):

  docs/reference/cli.md              block `cli`      — `voice-pipes --help` and every subcommand's help
  docs/reference/cargo-features.md   block `features` — the `[features]` table of voice-pipes/Cargo.toml
  docs/reference/cargo-features.md   block `cli-features` — the `[features]` table of voice-pipes-cli/Cargo.toml
  docs/reference/providers.md        whole file       — the config wizard's provider descriptor tables

Drift checks (hand-written pages must mention every enumerable item):

  every wizard provider id            -> docs/guides/providers/README.md
  every `PipelineEvent` variant       -> docs/reference/events.md (snake_case)
  every `[features]` key (both crates) -> docs/reference/cargo-features.md
  every `PipelineConfig` field        -> docs/reference/config.md

Usage:
    python scripts/gen-reference.py [--bin PATH]          # regenerate in place
    python scripts/gen-reference.py --check [--bin PATH]  # exit 1 if anything is stale or drifted

`--bin` is the voice-pipes binary (default: target/debug/voice-pipes[.exe],
then target/release/...). CI runs the check after building the CLI crate.
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DOCS = REPO / "docs"
CARGO = REPO / "voice-pipes" / "Cargo.toml"
CLI_CARGO = REPO / "voice-pipes-cli" / "Cargo.toml"
PROVIDERS_RS = REPO / "voice-pipes" / "src" / "commands" / "config_wizard" / "providers.rs"
EVENTS_RS = REPO / "voice-pipes" / "src" / "pipeline" / "events.rs"
TYPES_RS = REPO / "voice-pipes" / "src" / "config" / "types.rs"
METRICS_JSON = REPO / "voice-pipes-admin" / "backend" / "app" / "captures" / "metric_descriptors.json"

MARK = "<!-- generated:{kind} {name} -->"
HEADER_NOTE = "<!-- Generated by scripts/gen-reference.py — do not edit inside the markers. -->"


# ---------------------------------------------------------------------------
# helpers
# ---------------------------------------------------------------------------
def find_bin(explicit: str | None) -> Path:
    if explicit:
        return Path(explicit)
    for rel in ("target/debug/voice-pipes.exe", "target/debug/voice-pipes",
                "target/release/voice-pipes.exe", "target/release/voice-pipes"):
        p = REPO / rel
        if p.exists():
            return p
    sys.exit("voice-pipes binary not found; build with `cargo build -p voice-pipes-cli` or pass --bin")


def replace_block(text: str, name: str, body: str) -> tuple[str, bool]:
    """Return (new_text, changed). Markers must already exist."""
    start, end = MARK.format(kind="start", name=name), MARK.format(kind="end", name=name)
    if start not in text or end not in text:
        sys.exit(f"markers for block '{name}' not found")
    pre, rest = text.split(start, 1)
    _, post = rest.split(end, 1)
    new = f"{pre}{start}\n{HEADER_NOTE}\n{body.rstrip()}\n{end}{post}"
    return new, new != text


def read(p: Path) -> str:
    return p.read_text(encoding="utf-8")


def write(p: Path, s: str) -> None:
    p.write_text(s, encoding="utf-8", newline="")


# ---------------------------------------------------------------------------
# CLI block
# ---------------------------------------------------------------------------
def help_text(binary: Path, *args: str) -> str:
    out = subprocess.run([str(binary), *args, "--help"], capture_output=True, text=True, check=True).stdout
    # Windows prints `voice-pipes.exe`; normalise so the output is platform-independent.
    return out.replace("voice-pipes.exe", "voice-pipes").rstrip()


def gen_cli(binary: Path) -> str:
    top = help_text(binary)
    cmds: list[str] = []
    in_cmds = False
    for line in top.splitlines():
        if line.startswith("Commands:"):
            in_cmds = True
            continue
        if in_cmds:
            if not line.strip():
                break
            name = line.split()[0]
            if name != "help":
                cmds.append(name)
    parts = ["## Synopsis", "", "Output of `voice-pipes --help` and of every subcommand's `--help`.", "",
             "```text", top, "```", ""]
    for c in cmds:
        parts += [f"### `{c}`", "", "```text", help_text(binary, c), "```", ""]
    return "\n".join(parts)


# ---------------------------------------------------------------------------
# Cargo features block
# ---------------------------------------------------------------------------
class Features:
    """A manifest's `[features]`: the default set, one row per feature as
    (group, name, deps, comment), and each group's intro paragraph."""

    def __init__(self) -> None:
        self.default: list[str] = []
        self.rows: list[tuple[str, str, str, str]] = []
        self.intros: dict[str, str] = {}


def parse_features(cargo: Path = CARGO) -> Features:
    """Groups are the `# ── name ──` banner comments. A `#` paragraph directly
    under a banner and closed by a blank line describes the group; otherwise a
    feature's comment is the `#` lines directly above it."""
    text = read(cargo)
    m = re.search(r"^\[features\]\n(.*?)(?=^\[|\Z)", text, re.S | re.M)
    if not m:
        sys.exit("no [features] section")
    section = m.group(1)
    feats = Features()
    rows = feats.rows
    group = ""
    pending_comment: list[str] = []
    after_banner = False
    buf = ""
    key = ""
    for line in section.splitlines():
        s = line.strip()
        if buf:  # continuation of a multi-line list
            buf += " " + s
            if s.endswith("]"):
                deps = re.sub(r"\s+", " ", buf.strip("[] ")).replace('"', "")
                rows.append((group, key, deps, " ".join(pending_comment)))
                pending_comment, buf, key = [], "", ""
            continue
        if not s:
            if after_banner:
                feats.intros[group] = " ".join(pending_comment)
            pending_comment, after_banner = [], False
            continue
        if s.startswith("#"):
            hdr = re.match(r"#\s*─+\s*(.+?)\s*─+", s)
            if hdr:
                group = hdr.group(1).strip()
                pending_comment, after_banner = [], True
            else:
                pending_comment.append(s.lstrip("# ").strip())
            continue
        after_banner = False
        km = re.match(r'^([A-Za-z0-9_-]+)\s*=\s*(\[.*)$', s)
        if not km:
            continue
        key, rhs = km.group(1), km.group(2)
        if key == "default":
            feats.default = re.findall(r'"([^"]+)"', rhs)
            pending_comment = []
            continue
        if rhs.endswith("]"):
            deps = re.sub(r"\s+", " ", rhs.strip("[] ")).replace('"', "")
            rows.append((group, key, deps, " ".join(pending_comment)))
            pending_comment = []
        else:
            buf = rhs
    return feats


def gen_features() -> str:
    feats = parse_features()
    if feats.default:
        lead = "Default features: " + ", ".join(f"`{d}`" for d in feats.default) + "."
    else:
        lead = ("No default features: the engine adds only the providers named. "
                "`batteries` is the set the CLI builds of the engine by default; "
                "the CLI adds the plugins named in its `default-plugins` list.")
    out = ["## Feature list", "", "From `voice-pipes/Cargo.toml`. " + lead, ""]
    return "\n".join(out + feature_tables(feats)) + "\n"


def feature_tables(feats: Features) -> list[str]:
    """One table per group, in manifest order, under the group's intro."""
    out: list[str] = []
    current = None
    for group, name, deps, comment in feats.rows:
        if group != current:
            current = group
            out += ["", f"### {group or 'Other'}", ""]
            if feats.intros.get(group):
                out += [feats.intros[group], ""]
            out += ["| Feature | Enables | Notes |", "|---|---|---|"]
        deps_fmt = ", ".join(f"`{d.strip()}`" for d in deps.split(",") if d.strip()) or "—"
        out.append(f"| `{name}` | {deps_fmt} | {comment} |")
    return out


def crate_description(crate: str) -> str:
    """The `description` of a workspace crate, up to its first dash clause."""
    manifest = REPO / crate / "Cargo.toml"
    if not manifest.exists():
        return ""
    m = re.search(r'^description\s*=\s*"([^"]*)"', read(manifest), re.M)
    return m.group(1).split(" — ")[0].strip() if m else ""


def gen_cli_features() -> str:
    """The CLI crate's `[features]`: engine pass-throughs and the plugin crates
    it links. A plugin feature without a manifest comment takes the plugin
    crate's own `description`; an alias of other features says what it names."""
    feats = parse_features(CLI_CARGO)
    names = {name for _, name, _, _ in feats.rows}
    filled: list[tuple[str, str, str, str]] = []
    for group, name, deps, comment in feats.rows:
        parts = [d.strip() for d in deps.split(",") if d.strip()]
        if not comment:
            plugins = [p[len("dep:"):] for p in parts if p.startswith("dep:voice-pipes-")]
            if plugins:
                comment = crate_description(plugins[0])
            elif parts and all(p in names for p in parts):
                comment = "An alias: " + " with ".join(f"`{p}`" for p in parts) + "."
        if comment and not comment.endswith((".", ")")):
            comment += "."
        filled.append((group, name, deps, comment))
    feats.rows = filled
    out = ["## CLI feature list", "",
           "From `voice-pipes-cli/Cargo.toml`. Default features: " + ", ".join(f"`{d}`" for d in feats.default) + ".",
           "`default-plugins` in `[package.metadata.voice-pipes]` names the plugin features among them.", ""]
    return "\n".join(out + feature_tables(feats)) + "\n"


# ---------------------------------------------------------------------------
# Providers page (from the wizard descriptor tables)
# ---------------------------------------------------------------------------
def parse_providers() -> dict[str, list[dict[str, str]]]:
    """The built-in entries of each stage, read from `builtin_choices`: a
    `local(label, registry key, feature, field)` entry is a downloaded model,
    a `turn(label, timeout)` entry is built in."""
    text = read(PROVIDERS_RS)
    body = text[text.index("pub fn builtin_choices("):]
    tables: dict[str, list[dict[str, str]]] = {}
    arms = list(re.finditer(r"Stage::(\w+)(?: \| Stage::\w+)* => ", body))
    for i, arm in enumerate(arms):
        end = arms[i + 1].start() if i + 1 < len(arms) else len(body)
        chunk = body[arm.end():end]
        entries = []
        for m in re.finditer(r'\(\s*"([^"]+)"\.into\(\),\s*(local|turn)\(\s*"([^"]+)"(?:,\s*"([^"]+)",\s*"([^"]+)")?', chunk):
            provider, kind, label, _key, feature = m.groups()
            entries.append({
                "label": label,
                "provider": provider,
                "feature": feature if kind == "local" and feature else "—",
                "key_env": "—",
                "deploy": "downloaded model" if kind == "local" else "built in",
            })
        tables[arm.group(1).upper()] = entries
    return tables


STAGE_TITLES = {"STT": "Speech-to-text", "LLM": "LLM / text processor", "TTS": "Text-to-speech",
                "TURN": "Turn detection", "REALTIME": "Speech-to-speech (realtime)"}


def gen_providers_page() -> str:
    tables = parse_providers()
    out = ["# Providers (wizard descriptor tables)", "",
           "**Status:** active", "**Last verified:** generated", "**Owner:** Docs", "",
           "Every option the setup wizard offers, generated from the descriptor tables in",
           "`voice-pipes/src/commands/config_wizard/providers.rs` by `scripts/gen-reference.py`.",
           "The `provider` column is the value written to the TOML (`provider =`, `type =` or",
           "`mode =`); the [providers guide](../guides/providers/README.md) has a page per provider.", "",
           "Plugin providers are not in these tables: each plugin crate exports its own",
           "wizard entries (`wizard_choices()`), which the binary registers and the wizard",
           "lists with the built-in options of their stage, by `menu_rank`. They are",
           "listed in the providers guide. Every recogniser, voice, text processor and",
           "speech-to-speech provider is a plugin, so only turn detection has a table with rows here.", "",
           MARK.format(kind="start", name="providers"), HEADER_NOTE]
    for stage in ("STT", "LLM", "TTS", "TURN"):
        rows = tables.get(stage, [])
        out += ["", f"## {STAGE_TITLES.get(stage, stage)}", "",
                "| Wizard option | `provider` | Cargo feature | Provisioning | Key / credential env |",
                "|---|---|---|---|---|"]
        for r in rows:
            feat = f"`{r['feature']}`" if r["feature"] != "—" else "— (always compiled in)"
            out.append(f"| {r['label']} | `{r['provider']}` | {feat} | {r['deploy']} | {r['key_env']} |")
    out += [MARK.format(kind="end", name="providers"), ""]
    return "\n".join(out)


# ---------------------------------------------------------------------------
# Drift checks
# ---------------------------------------------------------------------------
def snake(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def event_variants() -> list[str]:
    text = read(EVENTS_RS)
    m = re.search(r"pub enum PipelineEvent \{(.*?)\n\}", text, re.S)
    body = m.group(1) if m else ""
    return [snake(v) for v in re.findall(r"^\s{4}([A-Z][A-Za-z]+)\s*(?:\{|,)", body, re.M)]


def config_fields() -> list[str]:
    text = read(TYPES_RS)
    m = re.search(r"pub struct PipelineConfig \{(.*?)\n\}", text, re.S)
    body = m.group(1) if m else ""
    fields = re.findall(r"^\s{4}pub ([a-z_]+):", body, re.M)
    renames = dict(re.findall(r'rename = "([a-z_]+)"[^\n]*\n\s*pub ([a-z_]+):', body))
    # renames maps new->old; invert for lookup
    inv = {v: k for k, v in renames.items()}
    return [inv.get(f, f) for f in fields]


def drift() -> list[str]:
    problems: list[str] = []
    providers_readme = read(DOCS / "guides" / "providers" / "README.md")
    for stage, rows in parse_providers().items():
        for r in rows:
            if f"`{r['provider']}`" not in providers_readme:
                problems.append(f"providers/README.md does not mention wizard provider `{r['provider']}` ({stage})")
    events_md = read(DOCS / "reference" / "events.md")
    for v in event_variants():
        if f"`{v}`" not in events_md:
            problems.append(f"reference/events.md does not mention PipelineEvent `{v}`")
    features_md = read(DOCS / "reference" / "cargo-features.md")
    for cargo in (CARGO, CLI_CARGO):
        crate = cargo.parent.name
        for _, name, _, _ in parse_features(cargo).rows:
            if f"`{name}`" not in features_md:
                problems.append(f"reference/cargo-features.md does not mention {crate} feature `{name}`")
    config_md = read(DOCS / "reference" / "config.md")
    for f in config_fields():
        if f"`{f}`" not in config_md and f"[{f}]" not in config_md and f"[[{f}]]" not in config_md:
            problems.append(f"reference/config.md does not mention PipelineConfig field `{f}`")
    return problems


# ---------------------------------------------------------------------------
# Metrics glossary and JSON export
# ---------------------------------------------------------------------------
def gen_metrics(binary: Path) -> tuple[str, str]:
    """Generate Markdown tables for docs/reference/metrics-glossary.md and
    the JSON export for voice-pipes-admin."""
    out = subprocess.run(
        [str(binary), "inspect", "--metrics", "--format", "json"],
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    descriptors = json.loads(out)
    lines: list[str] = []
    for comp in descriptors:
        kind = comp["kind"]
        label = comp["label"]
        lines.append(f"## {label} (`kind: \"{kind}\"`)")
        lines.append("")
        lines.append("| Key | Unit | Owner | Anchors | Meaning / Includes |")
        lines.append("|---|---|---|---|---|")
        for f in comp["fields"]:
            key = f"`{f['key']}`"
            unit = f"`{f['unit']}`"
            owner = f"`{f.get('owner', '—')}`"
            start = f.get("start_anchor", "—")
            end = f.get("end_anchor", "—")
            anchors = f"`{start}` → `{end}`" if start != "—" and end != "—" else "—"
            if f.get("contained_in"):
                anchors += f"<br>*(contained in `{f['contained_in']}`)*"
            includes = f.get("includes", f.get("label", ""))
            lines.append(f"| {key} | {unit} | {owner} | {anchors} | {includes} |")
        lines.append("")
    md_body = "\n".join(lines).rstrip()
    json_export = json.dumps(descriptors, indent=2) + "\n"
    return md_body, json_export


# ---------------------------------------------------------------------------
def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--bin")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    binary = find_bin(args.bin)

    metrics_md, metrics_json = gen_metrics(binary)

    targets = [
        (DOCS / "reference" / "cli.md", "cli", gen_cli(binary)),
        (DOCS / "reference" / "cargo-features.md", "features", gen_features()),
        (DOCS / "reference" / "cargo-features.md", "cli-features", gen_cli_features()),
        (DOCS / "reference" / "metrics-glossary.md", "metrics", metrics_md),
    ]
    stale: list[str] = []
    # A page may hold several blocks; apply them all before comparing.
    for path in dict.fromkeys(p for p, _, _ in targets):
        old = new = read(path)
        for target_path, name, body in targets:
            if target_path == path:
                new, _ = replace_block(new, name, body)
        if new != old:
            stale.append(path.relative_to(REPO).as_posix())
            if not args.check:
                write(path, new)
    ppath = DOCS / "reference" / "providers.md"
    pnew = gen_providers_page()
    if not ppath.exists() or read(ppath) != pnew:
        stale.append(ppath.relative_to(REPO).as_posix())
        if not args.check:
            write(ppath, pnew)

    if not METRICS_JSON.exists() or read(METRICS_JSON) != metrics_json:
        stale.append(METRICS_JSON.relative_to(REPO).as_posix())
        if not args.check:
            METRICS_JSON.parent.mkdir(parents=True, exist_ok=True)
            write(METRICS_JSON, metrics_json)

    problems = drift()
    if args.check:
        for s in stale:
            print(f"STALE   {s} (run scripts/gen-reference.py)")
        for p in problems:
            print(f"DRIFT   {p}")
        if stale or problems:
            return 1
        print("gen-reference: reference pages are current and hand-written pages cover every enumerable item.")
        return 0
    for s in stale:
        print(f"regenerated {s}")
    for p in problems:
        print(f"DRIFT   {p}")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
