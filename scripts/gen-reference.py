# ---------------------------------------------------------------------------
# Drift checks
# ---------------------------------------------------------------------------
def snake(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def event_variants() -> list[str]:
    text = read(EVENTS_RS)
    m = re.search(r"pub enum PipelineEvent \{(.*?)\n\}", text, re.S)
    body = m.group(1) if m else ""
    return [snake(v) for v in re.findall(r"^\s{4}([A-Z][A-Za-z]+)\s*(?:\{|,)", body, re.M)]


def config_fields() -> list[str]:
    text = read(TYPES_RS)
    m = re.search(r"pub struct PipelineConfig \{(.*?)\n\}", text, re.S)
    body = m.group(1) if m else ""
    fields = re.findall(r"^\s{4}pub ([a-z_]+):", body, re.M)
    renames = dict(re.findall(r'rename = "([a-z_]+)"[^\n]*\n\s*pub ([a-z_]+):', body))
    # renames maps new->old; invert for lookup
    inv = {v: k for k, v in renames.items()}
    return [inv.get(f, f) for f in fields]


def drift() -> list[str]:
    problems: list[str] = []
    providers_readme = read(DOCS / "guides" / "providers" / "README.md")
    for stage, rows in parse_providers().items():
        for r in rows:
            if f"`{r['provider']}`" not in providers_readme:
                problems.append(f"providers/README.md does not mention wizard provider `{r['provider']}` ({stage})")
    events_md = read(DOCS / "reference" / "events.md")
    for v in event_variants():
        if f"`{v}`" not in events_md:
            problems.append(f"reference/events.md does not mention PipelineEvent `{v}`")
    features_md = read(DOCS / "reference" / "cargo-features.md")
    for cargo in (CARGO, CLI_CARGO):
        crate = cargo.parent.name
        for _, name, _, _ in parse_features(cargo).rows:
            if f"`{name}`" not in features_md:
                problems.append(f"reference/cargo-features.md does not mention {crate} feature `{name}`")
    config_md = read(DOCS / "reference" / "config.md")
    for f in config_fields():
        if f"`{f}`" not in config_md and f"[{f}]" not in config_md and f"[[{f}]]" not in config_md:
            problems.append(f"reference/config.md does not mention PipelineConfig field `{f}`")
    return problems


