#!/usr/bin/env python3
"""Generate the enumerable parts of docs/reference/ from the code, and check
hand-written reference pages for drift.

Generated (between `<!-- generated:start NAME -->` / `<!-- generated:end NAME -->`
markers, so the prose around them stays hand-written):

  docs/reference/cli.md              block `cli`      — `voice-pipes --help` and every subcommand's help
  docs/reference/cargo-features.md   block `features` — the `[features]` table of voice-pipes/Cargo.toml
  docs/reference/cargo-features.md   block `cli-features` — the `[features]` table of voice-pipes-cli/Cargo.toml
  docs/reference/providers.md        whole file       — the config wizard's provider descriptor tables

Drift checks (hand-written pages must mention every enumerable item):

  every wizard provider id            -> docs/guides/providers/README.md
  every `PipelineEvent` variant       -> docs/reference/events.md (snake_case)
  every `[features]` key (both crates) -> docs/reference/cargo-features.md
  every `PipelineConfig` field        -> docs/reference/config.md

Usage:
    python scripts/gen-reference.py [--bin PATH]          # regenerate in place
    python scripts/gen-reference.py --check [--bin PATH]  # exit 1 if anything is stale or drifted

`--bin` is the voice-pipes binary (default: target/debug/voice-pipes[.exe],
then target/release/...). CI runs the check after building the CLI crate.
"""
