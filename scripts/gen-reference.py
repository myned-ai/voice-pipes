def find_bin(explicit: str | None) -> Path:
    if explicit:
        return Path(explicit)
    for rel in ("target/debug/voice-pipes.exe", "target/debug/voice-pipes",
                "target/release/voice-pipes.exe", "target/release/voice-pipes"):
        p = REPO / rel
        if p.exists():
            return p
    sys.exit("voice-pipes binary not found; build with `cargo build -p voice-pipes-cli` or pass --bin")


def replace_block(text: str, name: str, body: str) -> tuple[str, bool]:
    """Return (new_text, changed). Markers must already exist."""
    start, end = MARK.format(kind="start", name=name), MARK.format(kind="end", name=name)
    if start not in text or end not in text:
        sys.exit(f"markers for block '{name}' not found")
    pre, rest = text.split(start, 1)
    _, post = rest.split(end, 1)
    new = f"{pre}{start}\n{HEADER_NOTE}\n{body.rstrip()}\n{end}{post}"
    return new, new != text


def read(p: Path) -> str:
    return p.read_text(encoding="utf-8")


def write(p: Path, s: str) -> None:
    p.write_text(s, encoding="utf-8", newline="")


# ---------------------------------------------------------------------------
# CLI block
# ---------------------------------------------------------------------------
def help_text(binary: Path, *args: str) -> str:
    out = subprocess.run([str(binary), *args, "--help"], capture_output=True, text=True, check=True).stdout
    # Windows prints `voice-pipes.exe`; normalise so the output is platform-independent.
    return out.replace("voice-pipes.exe", "voice-pipes").rstrip()


def gen_cli(binary: Path) -> str:
    top = help_text(binary)
    cmds: list[str] = []
    in_cmds = False
    for line in top.splitlines():
        if line.startswith("Commands:"):
            in_cmds = True
            continue
        if in_cmds:
            if not line.strip():
                break
            name = line.split()[0]
            if name != "help":
                cmds.append(name)
    parts = ["## Synopsis", "", "Output of `voice-pipes --help` and of every subcommand's `--help`.", "",
             "```text", top, "```", ""]
    for c in cmds:
        parts += [f"### `{c}`", "", "```text", help_text(binary, c), "```", ""]
    return "\n".join(parts)


