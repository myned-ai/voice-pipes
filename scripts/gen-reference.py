class Features:
    """A manifest's `[features]`: the default set, one row per feature as
    (group, name, deps, comment), and each group's intro paragraph."""

    def __init__(self) -> None:
        self.default: list[str] = []
        self.rows: list[tuple[str, str, str, str]] = []
        self.intros: dict[str, str] = {}


def parse_features(cargo: Path = CARGO) -> Features:
    """Groups are the `# ── name ──` banner comments. A `#` paragraph directly
    under a banner and closed by a blank line describes the group; otherwise a
    feature's comment is the `#` lines directly above it."""
    text = read(cargo)
    m = re.search(r"^\[features\]\n(.*?)(?=^\[|\Z)", text, re.S | re.M)
    if not m:
        sys.exit("no [features] section")
    section = m.group(1)
    feats = Features()
    rows = feats.rows
    group = ""
    pending_comment: list[str] = []
    after_banner = False
    buf = ""
    key = ""
    for line in section.splitlines():
        s = line.strip()
        if buf:  # continuation of a multi-line list
            buf += " " + s
            if s.endswith("]"):
                deps = re.sub(r"\s+", " ", buf.strip("[] ")).replace('"', "")
                rows.append((group, key, deps, " ".join(pending_comment)))
                pending_comment, buf, key = [], "", ""
            continue
        if not s:
            if after_banner:
                feats.intros[group] = " ".join(pending_comment)
            pending_comment, after_banner = [], False
            continue
        if s.startswith("#"):
            hdr = re.match(r"#\s*─+\s*(.+?)\s*─+", s)
            if hdr:
                group = hdr.group(1).strip()
                pending_comment, after_banner = [], True
            else:
                pending_comment.append(s.lstrip("# ").strip())
            continue
        after_banner = False
        km = re.match(r'^([A-Za-z0-9_-]+)\s*=\s*(\[.*)$', s)
        if not km:
            continue
        key, rhs = km.group(1), km.group(2)
        if key == "default":
            feats.default = re.findall(r'"([^"]+)"', rhs)
            pending_comment = []
            continue
        if rhs.endswith("]"):
            deps = re.sub(r"\s+", " ", rhs.strip("[] ")).replace('"', "")
            rows.append((group, key, deps, " ".join(pending_comment)))
            pending_comment = []
        else:
            buf = rhs
    return feats


def gen_features() -> str:
    feats = parse_features()
    if feats.default:
        lead = "Default features: " + ", ".join(f"`{d}`" for d in feats.default) + "."
    else:
        lead = ("No default features: the engine adds only the providers named. "
                "`batteries` is the set the CLI builds of the engine by default; "
                "the CLI adds the plugins named in its `default-plugins` list.")
    out = ["## Feature list", "", "From `voice-pipes/Cargo.toml`. " + lead, ""]
    return "\n".join(out + feature_tables(feats)) + "\n"


def feature_tables(feats: Features) -> list[str]:
    """One table per group, in manifest order, under the group's intro."""
    out: list[str] = []
    current = None
    for group, name, deps, comment in feats.rows:
        if group != current:
            current = group
            out += ["", f"### {group or 'Other'}", ""]
            if feats.intros.get(group):
                out += [feats.intros[group], ""]
            out += ["| Feature | Enables | Notes |", "|---|---|---|"]
        deps_fmt = ", ".join(f"`{d.strip()}`" for d in deps.split(",") if d.strip()) or "—"
        out.append(f"| `{name}` | {deps_fmt} | {comment} |")
    return out


def crate_description(crate: str) -> str:
    """The `description` of a workspace crate, up to its first dash clause."""
    manifest = REPO / crate / "Cargo.toml"
    if not manifest.exists():
        return ""
    m = re.search(r'^description\s*=\s*"([^"]*)"', read(manifest), re.M)
    return m.group(1).split(" — ")[0].strip() if m else ""


def gen_cli_features() -> str:
    """The CLI crate's `[features]`: engine pass-throughs and the plugin crates
    it links. A plugin feature without a manifest comment takes the plugin
    crate's own `description`; an alias of other features says what it names."""
    feats = parse_features(CLI_CARGO)
    names = {name for _, name, _, _ in feats.rows}
    filled: list[tuple[str, str, str, str]] = []
    for group, name, deps, comment in feats.rows:
        parts = [d.strip() for d in deps.split(",") if d.strip()]
        if not comment:
            plugins = [p[len("dep:"):] for p in parts if p.startswith("dep:voice-pipes-")]
            if plugins:
                comment = crate_description(plugins[0])
            elif parts and all(p in names for p in parts):
                comment = "An alias: " + " with ".join(f"`{p}`" for p in parts) + "."
        if comment and not comment.endswith((".", ")")):
            comment += "."
        filled.append((group, name, deps, comment))
    feats.rows = filled
    out = ["## CLI feature list", "",
           "From `voice-pipes-cli/Cargo.toml`. Default features: " + ", ".join(f"`{d}`" for d in feats.default) + ".",
           "`default-plugins` in `[package.metadata.voice-pipes]` names the plugin features among them.", ""]
    return "\n".join(out + feature_tables(feats)) + "\n"


