def gen_metrics(binary: Path) -> tuple[str, str]:
    """Generate Markdown tables for docs/reference/metrics-glossary.md and
    the JSON export for voice-pipes-admin."""
    out = subprocess.run(
        [str(binary), "inspect", "--metrics", "--format", "json"],
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    descriptors = json.loads(out)
    lines: list[str] = []
    for comp in descriptors:
        kind = comp["kind"]
        label = comp["label"]
        lines.append(f"## {label} (`kind: \"{kind}\"`)")
        lines.append("")
        lines.append("| Key | Unit | Owner | Anchors | Meaning / Includes |")
        lines.append("|---|---|---|---|---|")
        for f in comp["fields"]:
            key = f"`{f['key']}`"
            unit = f"`{f['unit']}`"
            owner = f"`{f.get('owner', '—')}`"
            start = f.get("start_anchor", "—")
            end = f.get("end_anchor", "—")
            anchors = f"`{start}` → `{end}`" if start != "—" and end != "—" else "—"
            if f.get("contained_in"):
                anchors += f"<br>*(contained in `{f['contained_in']}`)*"
            includes = f.get("includes", f.get("label", ""))
            lines.append(f"| {key} | {unit} | {owner} | {anchors} | {includes} |")
        lines.append("")
    md_body = "\n".join(lines).rstrip()
    json_export = json.dumps(descriptors, indent=2) + "\n"
    return md_body, json_export


# ---------------------------------------------------------------------------
def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--bin")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    binary = find_bin(args.bin)

    metrics_md, metrics_json = gen_metrics(binary)

    targets = [
        (DOCS / "reference" / "cli.md", "cli", gen_cli(binary)),
        (DOCS / "reference" / "cargo-features.md", "features", gen_features()),
        (DOCS / "reference" / "cargo-features.md", "cli-features", gen_cli_features()),
        (DOCS / "reference" / "metrics-glossary.md", "metrics", metrics_md),
    ]
    stale: list[str] = []
    # A page may hold several blocks; apply them all before comparing.
    for path in dict.fromkeys(p for p, _, _ in targets):
        old = new = read(path)
        for target_path, name, body in targets:
            if target_path == path:
                new, _ = replace_block(new, name, body)
        if new != old:
            stale.append(path.relative_to(REPO).as_posix())
            if not args.check:
                write(path, new)
    ppath = DOCS / "reference" / "providers.md"
    pnew = gen_providers_page()
    if not ppath.exists() or read(ppath) != pnew:
        stale.append(ppath.relative_to(REPO).as_posix())
        if not args.check:
            write(ppath, pnew)

    if not METRICS_JSON.exists() or read(METRICS_JSON) != metrics_json:
        stale.append(METRICS_JSON.relative_to(REPO).as_posix())
        if not args.check:
            METRICS_JSON.parent.mkdir(parents=True, exist_ok=True)
            write(METRICS_JSON, metrics_json)

    problems = drift()
    if args.check:
        for s in stale:
            print(f"STALE   {s} (run scripts/gen-reference.py)")
        for p in problems:
            print(f"DRIFT   {p}")
        if stale or problems:
            return 1
        print("gen-reference: reference pages are current and hand-written pages cover every enumerable item.")
        return 0
    for s in stale:
        print(f"regenerated {s}")
    for p in problems:
        print(f"DRIFT   {p}")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
